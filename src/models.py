"""Data models for Agent Smith.

This module defines Pydantic schemas for tasks, execution steps,
sandbox configuration, and evaluation output contracts.
"""

from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, Field


class StepMetrics(BaseModel):
    """Metrics recorded for a single step in the agent loop.

    Attributes:
        step: 1-indexed iteration number.
        input_tokens: Tokens sent to LLM for this iteration.
        output_tokens: Tokens generated by LLM for this iteration.
        request_time_ms: LLM API latency in milliseconds.
        timestamp: ISO 8601 recording timestamp.
        api_url: URL of the LLM endpoint called.
        model_name: Model identifier used for this step.
        llm_output: Raw text output from LLM before code extraction.
        sandbox_input: Python code extracted and sent to sandbox.
        sandbox_output: Execution output (stdout/stderr) from sandbox.
        retries: Number of retries before successful API response.
    """
    step: int = Field(..., description="1-indexed iteration number")
    input_tokens: int = Field(
        ..., description="Tokens sent to the LLM for this step")
    output_tokens: int = Field(
        ..., description="Tokens generated by the LLM for this step")
    request_time_ms: float = Field(
        ..., description="Wall-clock time for the LLM API call in milliseconds"
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now().isoformat(),
        description="ISO 8601 timestamp of when this step was recorded")
    api_url: str = Field(
        default="",
        description="Base URL of the LLM API endpoint (e.g., "
        "'https://openrouter.ai/api/v1')")
    model_name: str = Field(
        default="",
        description="Model identifier used for this step (e.g., "
        "'qwen/qwen3-235b-a22b-2507')")
    llm_output: str = Field(
        default="",
        description="Raw text generated by the LLM before code extraction")
    sandbox_input: str = Field(
        default="",
        description="Python code sent to the sandbox for execution")
    sandbox_output: str = Field(
        default="",
        description="Sandbox execution result (stdout/stderr/error message)")
    retries: int = Field(
        default=0,
        description="Number of LLM API retries before getting a successful "
        "response (0 = first attempt succeeded)")


class SolutionOutput(BaseModel):
    """Final solution produced by the agent for moulinette validation.

    Attributes:
        task_id: Task identifier (string for both MBPP and SWE-bench).
        benchmark: Benchmark identifier ('mbpp' or 'swebench').
        success: Whether the agent considers the task solved.
        solution: Python function code for MBPP or git patch for SWE-bench.
        iterations: Total iterations executed.
        total_requests: Total LLM API calls made including retries.
        total_input_tokens: Cumulative prompt tokens across all steps.
        total_output_tokens: Cumulative generated tokens across all steps.
        total_time_seconds: Total wall-clock time from start to completion.
        steps: Detailed list of StepMetrics for each iteration.
        system_prompt: The initial system prompt sent to the model.
        error: Optional failure explanation if task was not completed.
        timestamp: ISO 8601 creation timestamp.
    """
    task_id: str = Field(
        ...,
        description="Task identifier (MBPP task_id as string, "
        "or SWE-bench instance_id)")
    benchmark: str = Field(
        ..., description="Benchmark type: 'mbpp' or 'swebench'")
    success: bool = Field(
        ..., description="Whether the agent believes it solved the task")
    solution: str = Field(
        ..., description="For MBPP: the Python function code. "
        "For SWE-bench: the git patch (diff)")
    iterations: int = Field(
        ..., description="Number of agent loop iterations used")
    total_requests: int = Field(
        ..., description="Total number of LLM API requests made "
        "(including retries)")
    total_input_tokens: int = Field(
        ..., description="Sum of input_tokens across all steps")
    total_output_tokens: int = Field(
        ..., description="Sum of output_tokens across all steps")
    total_time_seconds: float = Field(
        ..., description="Wall-clock time from agent start to finish")
    steps: List[StepMetrics] = Field(
        default_factory=list,
        description="Per-step metrics — one entry per agent iteration")
    system_prompt: str = Field(
        default="",
        description="Full system prompt sent to the LLM "
        "(for provenance checking)")
    error: Optional[str] = Field(
        default=None,
        description="Error message if the agent failed (None if successful)")
    timestamp: str = Field(
        default_factory=lambda: datetime.now().isoformat(),
        description="ISO 8601 timestamp of when the solution was produced")


class SandboxConfig(BaseModel):
    """Configuration settings and security limits for the sandbox.

    Attributes:
        authorized_imports: Whitelist of allowed Python module names.
        allowed_directories: Whitelist of accessible filesystem directories.
        max_execution_time_seconds: Timeout per code execution in seconds.
        max_memory_mb: RAM limit in megabytes.
    """
    authorized_imports: List[str] = Field(
        default_factory=lambda: [
            "math", "math.*",
            "collections", "collections.*",
            "itertools", "re", "json",
            "typing", "typing.*",
            "functools", "operator",
            "heapq", "bisect", "copy",
            "string", "random",
            "datetime", "datetime.*",
            "array", "cmath"],
        description="List of allowed import names (e.g., ['math', 'json', 're'"
        "]). Glob patterns like 'math.*' are supported.")
    allowed_directories: List[str] = Field(
        default_factory=lambda: ["/testbed", "/tmp/agent"],
        description="List of filesystem paths the sandbox can access "
        "(e.g., ['/testbed', '/tmp/agent'])")
    max_execution_time_seconds: int = Field(
        default=30,
        description="Maximum wall-clock time for a single "
        "sandbox execution before timeout")
    max_memory_mb: int = Field(
        default=512,
        description="Maximum memory in megabytes for sandbox execution")


class MBPPTaskInput(BaseModel):
    """Input payload representing an MBPP algorithmic task.

    Attributes:
        task_id: Integer identifier of the task.
        task_definition: Natural language problem description.
        function_definition: Target function signature.
        test_imports: Module imports required to execute the tests.
        test_list: Assertions used to validate the implementation.
    """
    task_id: int = Field(..., description="MBPP task identifier (integer)")
    task_definition: str = Field(
        ...,
        description="Natural language description of the function to implement"
    )
    function_definition: str = Field(
        ..., description="Function signature (e.g., 'def solve(nums):')")
    test_imports: List[str] = Field(
        default_factory=list,
        description="Import statements needed to run the public tests")
    test_list: List[str] = Field(
        default_factory=list,
        description="Public test assertions the solution must pass")


class SWEBenchTaskInput(BaseModel):
    """Input payload representing a SWE-bench repository issue.

    Attributes:
        instance_id: Unique task identifier (e.g. 'sympy__sympy-23534').
        problem_statement: GitHub issue description to resolve.
        docker_image: Full Docker image tag containing the repository.
        eval_script: Bash script to execute the task evaluation.
        hints_text: Optional hints or comments from the issue.
        repo: Repository name (e.g. 'sympy/sympy').
    """
    instance_id: str = Field(
        ...,
        description="SWE-bench instance identifier "
        "(e.g., 'sympy__sympy-23534')")
    problem_statement: str = Field(
        ...,
        description="The GitHub issue description — what needs to be fixed")
    docker_image: str = Field(
        ...,
        description="Full Docker image name to pull "
        "(e.g., 'swebench/sweb.eval.x86_64.sympy_1776_sympy-23534:latest')")
    eval_script: str = Field(
        ...,
        description="Bash script to run inside the container "
        "to evaluate the patch")
    hints_text: str = Field(
        default="",
        description="Optional hints about the issue (may be empty)")
    repo: str = Field(
        default="",
        description="Repository name (e.g., 'sympy/sympy')")
